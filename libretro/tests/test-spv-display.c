static void compare_layout(SpvDisplayShader shader,const GlslcLayout *layout)
{
    assert(shader.push_constant_size==layout->size && shader.num_push_constants==layout->count);
    for(size_t i=0;i<layout->count;i++){
        const ShaderUniform *a=shader.push_constants+i,*b=layout->members+i;
        assert(!strcmp(a->name,b->name) && a->offset==b->offset && a->dim_v==b->dim_v && a->dim_a==b->dim_a && a->stride==b->stride);
    }
}

