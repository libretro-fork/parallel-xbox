/* a * b as hi:lo */
static inline void vp_mul64(uint64_t a, uint64_t b, uint64_t *hi, uint64_t *lo)
{
#ifdef __SIZEOF_INT128__
    unsigned __int128 p = (unsigned __int128)a * b;
    *hi = (uint64_t)(p >> 64);
    *lo = (uint64_t)p;
#else
    uint64_t a0 = (uint32_t)a, a1 = a >> 32, b0 = (uint32_t)b, b1 = b >> 32;
    uint64_t p00 = a0 * b0, p01 = a0 * b1, p10 = a1 * b0, p11 = a1 * b1;
    uint64_t mid = (p00 >> 32) + (uint32_t)p01 + (uint32_t)p10;
    *lo = (mid << 32) | (uint32_t)p00;
    *hi = p11 + (p01 >> 32) + (p10 >> 32) + (mid >> 32);
#endif
}

/* (a * b) >> 62, floored, for a product below 2^126 */
static inline uint64_t vp_mul62(uint64_t a, uint64_t b)
{
    uint64_t hi, lo;

    vp_mul64(a, b, &hi, &lo);
    return (hi << 2) | (lo >> 62);
}

/* 2^(f / 2^62) in 1/2^62, for 0 <= f < 2^62: the product of the six 6-bit
 * levels, and 1 + r ln 2 for the last 26 bits (r ln 2 < 2^-35: the next
 * term is below 2^-71) */
static inline uint64_t vp_exp2_frac62(uint64_t f)
{
    uint64_t x = ((uint64_t)1 << 62) + vp_mul62(f & ((1u << 26) - 1),
                                                 VP_LN2_Q62);

    for (int k = 5; k >= 0; k--) {
        unsigned int i = (f >> (26 + 6 * (5 - k))) & 63;
        if (i) {
            x = vp_mul62(x, vp_exp2_levels[k][i]);
        }
    }
    return x;
}

/* The source step a sample, in 1/65536 of a source sample, for a pitch in
 * 1/2^14 of the register's 1/4096 octave: 2^(pitch / 4096) * 65536,
 * truncated */
static inline uint32_t vp_pitch_step(int64_t pitch14)
{
    int64_t oct = pitch14 >> 26;
    uint64_t mant = vp_exp2_frac62((uint64_t)(pitch14 - oct * (1 << 26)) << 36);
    int shift = 46 - (int)oct;

    if (shift <= 14) {
        return UINT32_MAX;
    }
    return shift >= 64 ? 0 : (uint32_t)(mant >> shift);
}

/* A filter cutoff coefficient (measured): k in 1/1024 octave below unity,
 * 2^(k / 1024) * 65536 rounded to nearest, at most 65535 */
static inline int32_t vp_cutoff_coefficient(int32_t k)
{
    int32_t oct = k >> 10;
    int shift = 46 - oct;

    if (oct >= 0) {
        return 65535;
    }
    if (shift >= 64) {
        return 0;
    }
    uint64_t mant = vp_exp2_frac62((uint64_t)(k & 1023) << 52);
    return (int32_t)((mant + ((uint64_t)1 << (shift - 1))) >> shift);
}

/* floor(a * e^(-n / d)), for a <= 2^16, n < 2^32, 0 < d < 2^31: the
 * envelopes' exponential decay and release. e^-x = 2^-z with
 * z = n log2(e) / d, in 1/2^62 */
static inline uint32_t vp_exp_decay(uint32_t a, uint32_t n, uint32_t d)
{
    uint64_t hi, lo, q_hi, q_lo, r, x;

    if (n == 0) {
        return a;
    }
    /* z = n * log2(e) / d: a 128-bit quotient, long division in 32-bit
     * steps (the remainder stays below d) */
    vp_mul64(n, VP_LOG2E_Q62, &hi, &lo);
    q_hi = hi / d;
    r = hi % d;
    x = (r << 32) | (lo >> 32);
    q_lo = (x / d) << 32;
    r = x % d;
    x = (r << 32) | (uint32_t)lo;
    q_lo |= x / d;
    uint64_t zi = (q_hi << 2) | (q_lo >> 62);
    uint64_t zf = q_lo & (((uint64_t)1 << 62) - 1);
    if (zi >= 64) {
        return 0;
    }
    if (zf == 0) {
        return a >> zi;
    }
    /* 2^-z = 2^-(zi + 1) * 2^(1 - zf), 2^(1 - zf) in [1, 2) */
    uint64_t mant = vp_exp2_frac62(((uint64_t)1 << 62) - zf);
    int shift = 63 + (int)zi;
    vp_mul64(a, mant, &hi, &lo);
    if (shift >= 128) {
        return 0;
    }
    if (shift >= 64) {
        return (uint32_t)(hi >> (shift - 64));
    }
    return (uint32_t)((hi << (64 - shift)) | (lo >> shift));
}

